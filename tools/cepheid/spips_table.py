"""Pulsation table of a Cepheid from a SPIPS model (Merand et al. 2015).

Usage:
    python spips_table.py <delcep2.dat> <distance_pc> <output.csv> [step]

Reads the "pulsation model data" table of VizieR J/A+A/584/A80 (delcep2.dat:
999 phases of the fitted model; ReadMe there) and writes every `step`-th row
(default 5) as the CSV a scene's `pulsation.table` points to:

    phase,radius_rsun,teff_k,luminosity_lsun

The radius is half the Rosseland angular diameter at the distance the model
was fitted for (274 pc for delta Cep, fixed in the paper). Phase 0 of the
model is the maximum of the bolometric light. Standard library only.
"""

import sys

MAS_TO_RAD = 3.141592653589793 / 180.0 / 3600.0e3
PARSEC_KM = 3.0856775814913673e13
SUN_RADIUS_KM = 695700.0  # IAU 2015 nominal


def main(src, distance_pc, dst, step):
    rows = []
    with open(src, encoding='ascii') as f:
        for line in f:
            if not line.strip():
                continue
            phase = float(line[0:8])
            diam_mas = float(line[31:38])
            teff = float(line[39:47])
            lum = float(line[48:56])
            radius = 0.5 * diam_mas * MAS_TO_RAD * distance_pc * PARSEC_KM / SUN_RADIUS_KM
            rows.append((phase, radius, teff, lum))
    with open(dst, 'w', encoding='ascii', newline='\n') as out:
        out.write('# SPIPS model of Merand et al. 2015 (A&A 584, A80; VizieR J/A+A/584/A80, '
                  f'{src.replace(chr(92), "/").split("/")[-1]}), every {step}th phase.\n')
        out.write(f'# Generated by tools/cepheid/spips_table.py; radius at {distance_pc:g} pc.\n')
        out.write('phase,radius_rsun,teff_k,luminosity_lsun\n')
        for phase, radius, teff, lum in rows[::step]:
            out.write(f'{phase:.6f},{radius:.4f},{teff:.1f},{lum:.1f}\n')
    print(f'{len(rows[::step])} of {len(rows)} phases written to {dst}')


if __name__ == '__main__':
    if len(sys.argv) not in (4, 5):
        sys.exit(__doc__)
    main(sys.argv[1], float(sys.argv[2]), sys.argv[3], int(sys.argv[4]) if len(sys.argv) == 5 else 5)
